-- V163 grants Secondary Titulaire class oversight, but V156 copied the old
-- Teacher compatibility DENY rows into secondary_teacher first.  Explicit
-- DENY wins over a later ALLOW, so remove only those generated compatibility
-- rows before the Titulaire grants are evaluated.

DELETE FROM permission_role_action
 WHERE role_code='secondary_teacher'
   AND action_code IN (
       'ACADEMIC_CLASS_RESULTS_VIEW',
       'ACADEMIC_REPORT_CARD_VIEW',
       'ACADEMIC_GRADE_PACKET_REVIEW',
       'ACADEMIC_COUNCIL_INPUT_VIEW',
       'ATTENDANCE_ROSTER_VIEW',
       'ATTENDANCE_REOPEN'
   )
   AND effect='DENY'
   AND reason='Secondary teacher copy: Permission Policy V2 compatibility backfill';

-- Re-assert the desired rules for existing schools.  Custom administrator
-- rules remain untouched; this is intentionally limited to the compatibility
-- rows generated by V118/V156 above.
INSERT INTO permission_role_action
    (school_id, role_code, action_code, effect, scope_mode, is_permanent, reason)
SELECT s.id, 'secondary_teacher', x.action_code, 'ALLOW', 'TITULAIRE_CLASSES', true, x.reason
  FROM school s
 CROSS JOIN (VALUES
    ('ACADEMIC_CLASS_RESULTS_VIEW', 'Secondary Titulaire class results read'),
    ('ACADEMIC_REPORT_CARD_VIEW', 'Secondary Titulaire report-card read'),
    ('ACADEMIC_GRADE_PACKET_REVIEW', 'Secondary Titulaire reviews all class subject packets'),
    ('ACADEMIC_COUNCIL_INPUT_VIEW', 'Secondary Titulaire council and attendance input read'),
    ('ATTENDANCE_ROSTER_VIEW', 'Secondary Titulaire class attendance read'),
    ('ATTENDANCE_REOPEN', 'Secondary Titulaire reopens finalized class attendance')
 ) x(action_code, reason)
 ON CONFLICT DO NOTHING;
